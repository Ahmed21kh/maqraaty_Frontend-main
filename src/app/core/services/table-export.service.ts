import { HttpClient } from '@angular/common/http';
import { inject, Injectable } from '@angular/core';
import { firstValueFrom } from 'rxjs';
import { API_URL } from '../config/api.config';

export interface ExportColumn<T = any> {
  header: string;
  /** Cell value for a row. Numbers stay numeric in Excel; everything else is text. */
  value: (row: T) => string | number | null | undefined;
  /** Excel column width in characters (otherwise measured from the data). */
  width?: number;
  /** Only include the column in these formats (default: all). */
  formats?: ('xlsx' | 'pdf' | 'doc')[];
}

export interface ExportOptions<T = any> {
  /** Shown at the top of the file (and used for the sheet name). */
  title: string;
  /** Optional second line, e.g. the active filter. */
  subtitle?: string;
  /** File name without extension. */
  fileName: string;
  columns: ExportColumn<T>[];
  rows: T[];
}

export type ExportFormat = 'xlsx' | 'pdf' | 'doc';

export interface ImportCheck {
  total: number;
  valid: number;
  invalid: { row: number; name: string; reason: string }[];
  preview: { row: number; name: string; phone_1: string; age: number | string; study_year: string; amount: number | string }[];
}

export interface ImportResult {
  created: { _id: string; code: number; name: string }[];
  skipped: { row: number; name: string; reason: string }[];
}

/**
 * Files are generated by the backend (`POST /api/export`): the page sends the table's columns and rows, and the server
 * returns a styled Excel sheet, a right-to-left PDF or a Word document. The browser only downloads the result, so
 * nothing heavy is bundled here. Student import goes through the backend too (`/api/import_students/...`).
 */
@Injectable({ providedIn: 'root' })
export class TableExportService {
  private readonly http = inject(HttpClient);
  private readonly api = inject(API_URL);

  async export<T>(format: ExportFormat, opts: ExportOptions<T>): Promise<void> {
    const columns = opts.columns.filter((c) => !c.formats || c.formats.includes(format));
    const body = {
      format,
      title: opts.title,
      subtitle: opts.subtitle ?? '',
      fileName: opts.fileName,
      color: this.themeColor(),
      columns: columns.map((c) => ({ header: c.header, width: c.width })),
      // plain arrays keep the request small
      rows: opts.rows.map((row) => columns.map((c) => c.value(row) ?? '')),
    };
    const blob = await firstValueFrom(this.http.post(`${this.api}export`, body, { responseType: 'blob' }));
    this.download(blob, `${opts.fileName}.${format}`);
  }

  async downloadStudentsTemplate(): Promise<void> {
    const blob = await firstValueFrom(this.http.get(`${this.api}import_students/template`, { responseType: 'blob' }));
    this.download(blob, 'نموذج استيراد الطلاب.xlsx');
  }

  /** Validates the sheet without saving anything. */
  checkStudentsFile(file: File): Promise<ImportCheck> {
    return firstValueFrom(this.http.post<ImportCheck>(`${this.api}import_students/file?dryRun=1`, this.form(file)));
  }

  importStudentsFile(file: File): Promise<ImportResult> {
    return firstValueFrom(this.http.post<ImportResult>(`${this.api}import_students/file`, this.form(file)));
  }

  private form(file: File): FormData {
    const fd = new FormData();
    fd.append('file', file);
    return fd;
  }

  /** The app's primary colour, so exported files match the theme. */
  private themeColor(): string {
    try {
      const v = getComputedStyle(document.documentElement).getPropertyValue('--app-primary').trim();
      return /^#[0-9a-f]{6}$/i.test(v) ? v : '';
    } catch {
      return '';
    }
  }

  private download(blob: Blob, name: string): void {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = name;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 10_000);
  }
}
